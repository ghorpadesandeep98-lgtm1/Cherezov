import type { NextConfig } from 'next';

const nextConfig: NextConfig = {
  reactStrictMode: true,
  images: {
    /*
     * AVIF впереди WebP. Оптимизатор отдаёт первый формат из списка, который
     * заявлен в заголовке `Accept` браузера, иначе следующий; по умолчанию
     * в списке только WebP, и AVIF не отдаётся вообще.
     *
     * Зачем. LCP мобильной главной — аэросъёмка первого экрана
     * (`/assets/v3/hero-aerial.jpg`, next/image fill + priority). На экране
     * 375 px при DPR 2 браузер берёт вариант `w=750`: до прихода этой картинки
     * первый экран пустой (FCP совпадает с её первой отрисовкой), поэтому её
     * вес — это и есть LCP. Выигрыш от AVIF растёт со снижением качества:
     * при q=75 AVIF и WebP равны (62,9 против 63,1 КБ), при q=60 — 28,7
     * против 51,2 КБ. Поэтому формат и качество правятся вместе.
     *
     * Риска для старых браузеров нет: формат выбирается по `Accept`, кто
     * не умеет AVIF — получает WebP, кто не умеет и его — исходный JPEG.
     * Плата — более долгая первая оптимизация на сервере; результат
     * кэшируется, поэтому платим один раз за вариант.
     */
    formats: ['image/avif', 'image/webp'],
  },
};

export default nextConfig;
